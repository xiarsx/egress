package boot

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// runBuild implements `egress build --with <module> [-o out]`
// (spec/ext-abi.md §4): generate a thin main package inside the CALLER's
// Go module that blank-imports the requested extension modules and calls
// boot.Main, then `go build` it. Run it from the module root that
// requires egress and the extension modules.
//
// The generated tree is temporary: <cwd>/.egress-build is created for
// the build and removed afterwards.
func runBuild(args []string) int {
	fs := flag.NewFlagSet("build", flag.ContinueOnError)
	var withs multiFlag
	fs.Var(&withs, "with", "extension module to blank-import (repeatable)")
	out := fs.String("o", "egress-custom", "output binary path")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if len(withs) == 0 {
		fmt.Fprintln(os.Stderr, "egress build: at least one --with <module> is required")
		return 2
	}
	if _, err := os.Stat("go.mod"); err != nil {
		fmt.Fprintln(os.Stderr, "egress build: run from a Go module root (go.mod not found)")
		return 1
	}

	dir := ".egress-build"
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "egress build: %v\n", err)
		return 1
	}
	defer os.RemoveAll(dir)

	var sb strings.Builder
	sb.WriteString("// Code generated by `egress build`. DO NOT COMMIT.\n\n")
	sb.WriteString("package main\n\nimport (\n\t\"os\"\n\n")
	sb.WriteString("\t\"github.com/xiarsx/egress/boot\"\n")
	for _, w := range withs {
		fmt.Fprintf(&sb, "\t_ %q\n", w)
	}
	sb.WriteString(")\n\nfunc main() { os.Exit(boot.Main()) }\n")
	mainPath := filepath.Join(dir, "main.go")
	if err := os.WriteFile(mainPath, []byte(sb.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "egress build: %v\n", err)
		return 1
	}

	cmd := exec.Command("go", "build", "-o", *out, "./"+dir)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		fmt.Fprintf(os.Stderr, "egress build: %v\n", err)
		return 1
	}
	fmt.Printf("egress build: %s (with %s)\n", *out, strings.Join(withs, ", "))
	return 0
}

// multiFlag collects repeatable -with flags.
type multiFlag []string

func (m *multiFlag) String() string { return strings.Join(*m, ",") }
func (m *multiFlag) Set(v string) error {
	*m = append(*m, v)
	return nil
}
